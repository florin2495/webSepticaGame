import { notifyRoom } from "@/lib/server/broadcast";
import { db, PLAYER_COLUMNS, type PlayerRow, T } from "@/lib/server/db";
import { fail, handle, readJson } from "@/lib/server/http";
import { removePlayer } from "@/lib/server/membership";
import { requireHost, requireMember } from "@/lib/server/room";

// POST /api/rooms/[code]/kick  { playerId } - host removes another player (lobby / finished: at once; during a deal: pending kick, see /kick/ignore).
// Not a ban: a kicked player could rejoin a lobby under a new nickname. The room password is the real protection.
export async function POST(req: Request, ctx: RouteContext<"/api/rooms/[code]/kick">) {
  return handle(async () => {
    const { code } = await ctx.params;
    const { room, player } = await requireMember(req, code);
    requireHost(room, player);

    const body = await readJson(req);
    const targetId = typeof body.playerId === "string" ? body.playerId : "";
    if (targetId === player.id) fail(400, "Nu te poți scoate singur. Folosește „Părăsește camera”.");

    const { data: target, error } = await db()
      .from(T.players)
      .select(PLAYER_COLUMNS)
      .eq("id", targetId)
      .eq("room_id", room.id)
      .maybeSingle();
    if (error && error.code !== "22P02") throw error; // 22P02 = malformed uuid
    if (!target) fail(404, "Jucătorul nu mai e în cameră.");

    // During a running deal a participant gets KICK_GRACE_MS to press "Ignoră"; everyone else goes at once.
    if (room.status === "playing" && room.deal?.order.includes(targetId)) {
      const { error: pendingError } = await db()
        .from(T.players)
        .update({ kick_requested_at: new Date().toISOString() })
        .eq("id", targetId)
        .is("kick_requested_at", null); // a second kick does not reset the deadline
      if (pendingError) throw pendingError;
      await notifyRoom(room.id, "kick_pending");
      return { ok: true, pending: true };
    }

    await removePlayer(room, target as PlayerRow, "player_kicked");
    return { ok: true };
  });
}
